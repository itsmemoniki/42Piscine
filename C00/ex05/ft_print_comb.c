#include <unistd.h>

void	ft_print_comb(void)
{
	char	i1;
	char	i2;
	char	i3;

	i1 = '0';
	while (i1 <= '7')
	{
		i2 = i1 + 1;
		while (i2 <= '8')
		{
			i3 = i2 + 1;
			while (i3 <= '9')
			{
				write (1, (char []){i1, i2, i3}, 3);
				if (i1 != '7')
				{
					write (1, ", ", 2);
				}
				i3++;
			}
			i2++;
		}
		i1++;
	}
}
